# 递归 DFS
# Python 3；直接运行文件，修改示例数据可继续练习。
# 进入当前位置并标记已发现。

g = [[1, 2], [0, 3, 4], [0, 5, 6], [1, 7], [1, 8, 5], [2, 4], [2, 9], [3], [4, 9], [6, 8]]
# 访问标记初始为空或全为假，表示还没有发现节点。
seen = set()

# 进入节点后标记，再逐个递归访问尚未发现的邻居。
def dfs(u):
    seen.add(u)
    # 输出计算结果，便于与课程例子或自行推演的答案核对。
    print(chr(65 + u), end=' ')
    for v in g[u]:
        if v not in seen:
            dfs(v)
dfs(0)
print()
