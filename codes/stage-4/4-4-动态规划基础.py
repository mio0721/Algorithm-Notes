# 先算出最小几个台阶的走法数。

# 保存到达每级台阶的方案数，后续状态只依赖前两级的结果。
def climb_stairs(n):
    if n < 0:
        # 不符合本算法前提的输入要明确拒绝，不能带着错误条件继续计算。
        raise ValueError('台阶数必须非负')
    dp = [0] * (n + 1)
    # 到0级时什么也不做，是一种完整方案。
    dp[0] = 1
    for i in range(1, n + 1):
        # 按最后一步来自前一级或前两级分类，不会重复计数。
        dp[i] = dp[i - 1] + (dp[i - 2] if i >= 2 else 0)
    return dp[n]

# 程序入口：准备示例数据，调用算法，并输出结果供手算核对。
def main():
    for n in [0, 1, 5, 9]:
        # 输出计算结果，便于与课程例子或自行推演的答案核对。
        print(n, climb_stairs(n))
if __name__ == '__main__':
    main()
