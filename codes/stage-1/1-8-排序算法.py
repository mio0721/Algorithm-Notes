# 排序算法
# Python 3；直接运行文件，修改示例数据可继续练习。
# 左边保留已经有序的部分。

a = [9, 3, 7, 1, 8, 2, 6, 4, 5]
for i in range(1, len(a)):
    value, j = (a[i], i - 1)
    # 把比待插入值大的元素向后挪；相等时不挪，保留稳定性。
    while j >= 0 and a[j] > value:
        a[j + 1] = a[j]
        j -= 1
    a[j + 1] = value
# 输出计算结果，便于与课程例子或自行推演的答案核对。
print(a)
