# 函数调用栈与递归返回
# Python 3；直接运行文件，修改示例数据可继续练习。
# 进入函数时，把本层参数和暂停位置放入调用栈。

# 先计算更小的前缀和，等待它返回后再加上当前数字。
def sum_to(n):
    # 输出计算结果，便于与课程例子或自行推演的答案核对。
    print('进入', n)
    if n == 0:
        # 下层结果回来后，才计算本层并继续向上一层返回。
        return 0
    # 此处调用下一层时，本层会暂停，局部参数仍保存在调用栈中。
    smaller = sum_to(n - 1)
    # 输出计算结果，便于与课程例子或自行推演的答案核对。
    print('返回', n)
    # 此处调用下一层时，本层会暂停，局部参数仍保存在调用栈中。
    return n + smaller
result = sum_to(2)
# 输出计算结果，便于与课程例子或自行推演的答案核对。
print('结果:', result)
